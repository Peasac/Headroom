def _handbook() -> str:
    parts = []
    for s, name in enumerate(_SECTIONS):
        sentences = [
            f"This section covers {name.lower()} for everyone at the Harbor Street office.",
            f"Questions about {name.lower()} go to the office manager, who replies within {s % 3 + 1} working days.",
            f"Rule {s + 1}.1: keep shared areas tidy and leave {name.lower()} equipment as you found it.",
            f"Rule {s + 1}.2: report problems with {name.lower()} on the internal form within {s + 2} days.",
            f"Rule {s + 1}.3: exceptions to the {name.lower()} rules need written approval from a director.",
            "These rules were last reviewed in October and apply to staff, contractors and interns alike.",
        ]
        if name == "IT":
            sentences.insert(3, "Staff wifi password: harbor-21. Do not share it with visitors.")
        if name == "Visitors":
            sentences.insert(2, "Guest wifi password: lantern-58. Give it to visitors on request.")
        parts.append(f"Section {s + 1}: {name}\n" + " ".join(sentences))
    return "\n\n".join(parts) + "\n"


