def _sales() -> tuple[str, str]:
    """(the whole CSV, its header plus every Islands row). 'Islands map' is a product, not a region."""
    header = "date,region,product,amount"
    rows, islands = [], []
    for i in range(140):
        date = f"2026-{9 + i // 60:02d}-{1 + i % 28:02d}"
        region = "Islands" if i in _ISLANDS_AT else _REGIONS[i % 5]
        row = f"{date},{region},{_PRODUCTS[(i * 7) % 6]},{(i * 37) % 400 + 20}"
        rows.append(row)
        if region == "Islands":
            islands.append(row)
    return "\n".join([header, *rows]) + "\n", "\n".join([header, *islands]) + "\n"


