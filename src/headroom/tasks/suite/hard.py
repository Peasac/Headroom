"""Tier-4 tuning tasks: hard by structure (definition in suite/files.py), two of each kind.

Long contents are generated by plain arithmetic (no RNG), so they are identical on every platform.
"""

from datetime import datetime, timedelta

from headroom.schemas.env import EnvState, Event, Note
from headroom.schemas.task import Count, EventExists, FileAbsent, FileEquals, NoteExists, Preserved, Task, Unchanged

FILE_TOOLS = ("read_file", "write_file", "rename_file", "list_files")
NOTE_TOOLS = ("read_file", "list_files", "add_note", "search_notes")
CAL_TOOLS = ("add_event", "list_events")
NO_NOTES_EVENTS = (Unchanged(scope="notes"), Unchanged(scope="events"))

# ---- long: application log with six ERROR lines ----
_ERROR_AT = {9: "payment gateway timeout order=88412", 22: "disk write failed path=/var/data/cache.db",
             37: "payment gateway timeout order=88530", 48: "worker crashed pid=4410 signal=11",
             61: "certificate expired host=api.internal", 70: "queue overflow size=10000 dropped=37"}
_PATHS = ("/api/items", "/api/cart", "/api/users", "/api/search", "/health")


def _app_log() -> tuple[str, str]:
    """(the whole log, just its ERROR lines). INFO lines sometimes say 'error_rate' in lower case."""
    t0 = datetime(2026, 11, 30, 8, 0, 0)
    lines, errors = [], []
    for i in range(75):
        ts = (t0 + timedelta(seconds=37 * i)).strftime("%Y-%m-%dT%H:%M:%S")
        if i in _ERROR_AT:
            line = f"{ts} ERROR {_ERROR_AT[i]}"
            errors.append(line)
        elif i % 13 == 5:
            line = f"{ts} WARN slow query id={1000 + i} ms={400 + (i * 17) % 300}"
        elif i % 9 == 0:
            line = f"{ts} INFO stats window=60s error_rate=0.0{i % 7} requests={200 + i}"
        else:
            line = f"{ts} INFO request id={1000 + i} path={_PATHS[i % 5]} ms={(i * 29) % 180 + 5}"
        lines.append(line)
    return "\n".join(lines) + "\n", "\n".join(errors) + "\n"


APP_LOG, APP_LOG_ERRORS = _app_log()

# ---- long: meeting transcript with four decisions ----
_NAMES = ("Ana", "Tom", "Priya", "Marta")
_TOPICS = ("payroll vendor", "offsite venue", "release train", "support rota", "hiring plan", "office move")
_DECISIONS = {
    23: "DECISION: switch the payroll vendor to Kestrel (owner: Priya)",
    47: "DECISION: hold the offsite in Lisbon (owner: Tom)",
    71: "DECISION: move the release train to every second Tuesday (owner: Ana)",
    95: "DECISION: hire two support engineers in Q1 (owner: Marta)",
}
_PROPOSALS = {
    35: "PROPOSAL (rejected): switch the payroll vendor to Brightpay (owner: Tom)",
    83: "PROPOSAL (rejected): hold the offsite in Porto (owner: Priya)",
}


def _minutes() -> str:
    lines = ["Planning meeting, full transcript, 2026-11-20", "Attendees: Ana, Tom, Priya, Marta", ""]
    for i in range(110):
        if i in _DECISIONS:
            lines.append(_DECISIONS[i])
        elif i in _PROPOSALS:
            lines.append(_PROPOSALS[i])
        else:
            who, topic = _NAMES[i % 4], _TOPICS[(i * 5) % 6]
            other = _NAMES[(i + 1) % 4]
            lines.append(f"{who}: on the {topic}, I'd like {other} to check the numbers again before item {i + 1}.")
    return "\n".join(lines) + "\n"


MINUTES = _minutes()

# ---- chain ----
_SCANS = {f"scans/r{i}.txt": f"Receipt {i}: {12 * i + 3}.50 EUR\n" for i in range(1, 6)}

# ---- recovery ----
_NEW_INVOICE = "Invoice 2026-12, ACME, 1,200 EUR\n"
_OLD_INVOICE = "Invoice 2026-11, ACME, 900 EUR\n"


def _exists(title: str, start: str, end: str) -> EventExists:
    return EventExists(title=title, start=datetime.fromisoformat(start), end=datetime.fromisoformat(end))


